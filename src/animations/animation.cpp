#include "face/face.h"

// =====================================================
// BLINK ANIMATION
// =====================================================

void blinkAnimation()
{
    // -------------------------------------------------
    // Close eyes
    // -------------------------------------------------

    tft.fillScreen(BG_COLOR);

    drawNormalEyebrows();

    // Left closed eye

    tft.drawLine(
        65,
        110,
        135,
        110,
        EYE_COLOR
    );

    // Right closed eye

    tft.drawLine(
        185,
        110,
        255,
        110,
        EYE_COLOR
    );

    drawCheeks();

    drawNormalMouth();

    delay(100);

    // -------------------------------------------------
    // Open eyes
    // -------------------------------------------------

    drawNormalFace();

    delay(100);
}


// =====================================================
// HAPPY ANIMATION
// =====================================================

void happyAnimation()
{
    // -------------------------------------------------
    // Start
    // -------------------------------------------------

    drawHappyFace(
        0,
        0
    );

    delay(150);

    // -------------------------------------------------
    // Move up
    // -------------------------------------------------

    drawHappyFace(
        0,
        -5
    );

    delay(100);

    // -------------------------------------------------
    // Move down
    // -------------------------------------------------

    drawHappyFace(
        0,
        5
    );

    delay(100);

    // -------------------------------------------------
    // Back to center
    // -------------------------------------------------

    drawHappyFace(
        0,
        0
    );

    delay(200);

    // -------------------------------------------------
    // Blink
    // -------------------------------------------------

    blinkAnimation();

    // -------------------------------------------------
    // Return normal
    // -------------------------------------------------

    drawNormalFace();
}


// =====================================================
// SLEEPY ANIMATION
// =====================================================

void sleepyAnimation()
{
    // -------------------------------------------------
    // Eyes slowly close
    // -------------------------------------------------

    for (int i = 0; i < 3; i++)
    {
        tft.fillScreen(BG_COLOR);

        drawSleepyEyebrows();

        int y = 108 + (i * 3);

        // Left eye

        tft.drawLine(
            70,
            y,
            130,
            y,
            EYE_COLOR
        );

        // Right eye

        tft.drawLine(
            190,
            y,
            250,
            y,
            EYE_COLOR
        );

        drawCheeks();

        drawSleepyMouth();

        delay(120);
    }

    // -------------------------------------------------
    // Stay sleepy
    // -------------------------------------------------

    delay(500);

    // -------------------------------------------------
    // Wake up
    // -------------------------------------------------

    for (int i = 0; i < 3; i++)
    {
        drawNormalFace();

        delay(100);
    }
}


// =====================================================
// SURPRISE ANIMATION
// =====================================================

void surprisedAnimation()
{
    // -------------------------------------------------
    // Start with normal face
    // -------------------------------------------------

    drawNormalFace();

    delay(100);

    // -------------------------------------------------
    // Expand eyes
    // -------------------------------------------------

    drawSurprisedFace(-3);

    delay(120);

    drawSurprisedFace(0);

    delay(120);

    drawSurprisedFace(3);

    delay(120);

    drawSurprisedFace(0);

    delay(500);

    // -------------------------------------------------
    // Return normal
    // -------------------------------------------------

    drawNormalFace();
}

// =====================================================
// DIZZY ANIMATION
// =====================================================

void dizzyAnimation()
{
    // -------------------------------------------------
    // Start dizzy
    // -------------------------------------------------

    drawDizzyFace(
        0,
        0
    );

    delay(100);


    // -------------------------------------------------
    // Shake left
    // -------------------------------------------------

    drawDizzyFace(
        -8,
        0
    );

    delay(80);


    // -------------------------------------------------
    // Shake right
    // -------------------------------------------------

    drawDizzyFace(
        8,
        0
    );

    delay(80);


    // -------------------------------------------------
    // Shake left again
    // -------------------------------------------------

    drawDizzyFace(
        -6,
        3
    );

    delay(80);


    // -------------------------------------------------
    // Shake right again
    // -------------------------------------------------

    drawDizzyFace(
        6,
        -3
    );

    delay(80);


    // -------------------------------------------------
    // Center
    // -------------------------------------------------

    drawDizzyFace(
        0,
        0
    );

    delay(300);


    // -------------------------------------------------
    // Recover
    // -------------------------------------------------

    drawNormalFace();

    delay(150);
}