#include "animation.h"

#include <Arduino.h>

#include "face/face.h"

// =====================================================
// BLINK ANIMATION
// =====================================================

void blink_animation()
{
    // -------------------------------------------------
    // Close eyes
    // -------------------------------------------------

    draw_blink_frame();
    delay(100);

    // -------------------------------------------------
    // Open eyes
    // -------------------------------------------------

    draw_normal_face();
    delay(100);
}

// =====================================================
// HAPPY ANIMATION
// =====================================================

void happy_animation()
{
    // -------------------------------------------------
    // Start
    // -------------------------------------------------

    draw_happy_face(0, 0);
    delay(150);

    // -------------------------------------------------
    // Move up
    // -------------------------------------------------

    draw_happy_face(0, -5);
    delay(100);

    // -------------------------------------------------
    // Move down
    // -------------------------------------------------

    draw_happy_face(0, 5);
    delay(100);

    // -------------------------------------------------
    // Back to center
    // -------------------------------------------------

    draw_happy_face(0, 0);
    delay(200);

    // -------------------------------------------------
    // Blink
    // -------------------------------------------------

    blink_animation();

    // -------------------------------------------------
    // Return normal
    // -------------------------------------------------

    draw_normal_face();
}

// =====================================================
// SLEEPY ANIMATION
// =====================================================

void sleepy_animation()
{
    // -------------------------------------------------
    // Eyes slowly close (lid drops 3px per frame)
    // -------------------------------------------------

    for (int i = 0; i < 3; i++)
    {
        draw_sleepy_frame(108 + (i * 3));
        delay(120);
    }

    // -------------------------------------------------
    // Stay sleepy
    // -------------------------------------------------

    delay(500);

    // -------------------------------------------------
    // Wake up
    // -------------------------------------------------

    for (int i = 0; i < 3; i++)
    {
        draw_normal_face();
        delay(100);
    }
}

// =====================================================
// SURPRISED ANIMATION
// =====================================================

void surprised_animation()
{
    // -------------------------------------------------
    // Start with normal face
    // -------------------------------------------------

    draw_normal_face();
    delay(100);

    // -------------------------------------------------
    // Expand eyes
    // -------------------------------------------------

    draw_surprised_face(-3);
    delay(120);

    draw_surprised_face(0);
    delay(120);

    draw_surprised_face(3);
    delay(120);

    draw_surprised_face(0);
    delay(500);

    // -------------------------------------------------
    // Return normal
    // -------------------------------------------------

    draw_normal_face();
}

// =====================================================
// DIZZY ANIMATION
// =====================================================

void dizzy_animation()
{
    // -------------------------------------------------
    // Start dizzy
    // -------------------------------------------------

    draw_dizzy_face(0, 0);
    delay(100);

    // -------------------------------------------------
    // Shake left
    // -------------------------------------------------

    draw_dizzy_face(-8, 0);
    delay(80);

    // -------------------------------------------------
    // Shake right
    // -------------------------------------------------

    draw_dizzy_face(8, 0);
    delay(80);

    // -------------------------------------------------
    // Shake left again
    // -------------------------------------------------

    draw_dizzy_face(-6, 3);
    delay(80);

    // -------------------------------------------------
    // Shake right again
    // -------------------------------------------------

    draw_dizzy_face(6, -3);
    delay(80);

    // -------------------------------------------------
    // Center
    // -------------------------------------------------

    draw_dizzy_face(0, 0);
    delay(300);

    // -------------------------------------------------
    // Recover
    // -------------------------------------------------

    draw_normal_face();
    delay(150);
}
